import { sql } from 'drizzle-orm';
import { drizzle } from 'drizzle-orm/node-postgres';
import pg from 'pg';
import * as schema from './schema.ts';

const { Pool } = pg;

export const pool = new Pool({
  host: process.env.DB_HOST || 'localhost',
  port: Number(process.env.DB_PORT || 5432),
  user: process.env.DB_USER || 'banco_sangre',
  password: process.env.DB_PASSWORD || 'banco_sangre_dev',
  database: process.env.DB_NAME || 'banco_sangre',
});

pool.on('error', (error) => {
  console.error('Unexpected error on idle PostgreSQL client:', error);
});

export const db = drizzle(pool, { schema });

export async function initializeDatabaseSchema(): Promise<void> {
  await db.execute(sql`
    CREATE TABLE IF NOT EXISTS ficha_medica (
      rut TEXT PRIMARY KEY,
      presion_arterial TEXT,
      frecuencia_cardiaca INTEGER,
      peso REAL,
      estado_clinico TEXT CHECK(estado_clinico IN ('listo para donar', 'Diferido')),
      tipo_sangre TEXT,
      fecha_elegibilidad TEXT,
      observaciones TEXT,
      fecha_actualizacion TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
    );
  `);

  await db.execute(sql`
    CREATE TABLE IF NOT EXISTS citas (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      rut TEXT NOT NULL,
      sede TEXT NOT NULL,
      fecha TEXT NOT NULL,
      hora TEXT NOT NULL,
      estado TEXT DEFAULT 'agendada' CHECK(estado IN ('agendada', 'cancelada', 'realizada')),
      fecha_creacion TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
    );
  `);
}
